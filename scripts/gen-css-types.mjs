#!/usr/bin/env node
// scripts/gen-css-types.mjs
//
// ADR 0023 — generate a `.d.ts` next to every `*.module.css` so `styles.typo` is a compile
// error rather than a silently unstyled element.
//
// The generated declaration WINS over the ambient `declare module '*.module.css'` fallback in
// packages/theme/src/css-modules.d.ts, because a file-specific module declaration beats a
// wildcard. The fallback exists only so a fresh clone type-checks before anyone runs this.
//
// Why not `happy-css-modules`: it is a fine tool, but it declares a hard Node engine range
// that CI would have to satisfy for one script, and it does not understand `composes` across
// files the way this repo uses it. The parsing needed here is small and explicit — collect
// class selectors, camel-case them, emit a typed object — and doing it in-repo keeps the
// generator and the bundler's `localsConvention: 'camelCaseOnly'` visibly in agreement.
//
// Usage:
//   node scripts/gen-css-types.mjs
//   node scripts/gen-css-types.mjs --check      fail on drift or on a missing/orphaned file
//   node scripts/gen-css-types.mjs --self-test

import {
  readFileSync,
  writeFileSync,
  rmSync,
  mkdirSync,
  readdirSync,
  statSync,
  existsSync,
  unlinkSync,
} from 'node:fs';
import { resolve, relative, join, sep, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(import.meta.url), '..', '..');
const PACKAGES = resolve(repoRoot, 'packages');

function walk(dir, predicate, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'dist' || entry.startsWith('.')) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, predicate, out);
    else if (predicate(full)) out.push(full);
  }
  return out;
}

/**
 * Collect class names from a stylesheet. Deliberately simple: strip comments and strings,
 * then take every `.identifier` that is not inside a `@media`/`@supports` prelude. A CSS
 * parser would be more correct in the abstract, but this repo's stylesheets are hand-written
 * component modules — no preprocessor, no interpolation — and an extra dependency here buys
 * nothing that `--check` in CI does not already catch.
 */
function classNamesOf(css) {
  const cleaned = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/"[^"]*"|'[^']*'/g, '""');
  const names = new Set();
  for (const match of cleaned.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
    const name = match[1];
    // A leading `_` marks a private custom-property helper, never a class a component reads.
    if (name.startsWith('_')) continue;
    names.add(name);
  }
  return [...names].sort();
}

function toCamel(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function render(cssPath, names) {
  const rel = relative(repoRoot, cssPath).split(sep).join('/');
  const keys = [...new Set(names.map(toCamel))].sort();
  return `// GENERATED by scripts/gen-css-types.mjs from ${basename(cssPath)} — do not edit.
// Source: ${rel}. Run \`npm run gen:css-types\` after adding or renaming a class (ADR 0023).

declare const styles: {
${keys.map((k) => `  readonly ${k}: string;`).join('\n')}
};
export default styles;
`;
}

function build() {
  const sheets = walk(PACKAGES, (f) => f.endsWith('.module.css'));
  return sheets.map((cssPath) => ({
    cssPath,
    dtsPath: `${cssPath}.d.ts`,
    content: render(cssPath, classNamesOf(readFileSync(cssPath, 'utf8'))),
  }));
}

/** A `.module.css.d.ts` whose stylesheet is gone is a declaration for a module that no longer exists. */
function orphans() {
  return walk(PACKAGES, (f) => f.endsWith('.module.css.d.ts')).filter(
    (dts) => !existsSync(dts.slice(0, -'.d.ts'.length)),
  );
}

const argv = process.argv.slice(2);

if (argv.includes('--self-test')) {
  const fixtureDir = resolve(PACKAGES, 'theme/src/__csstypecheck__');
  const css = join(fixtureDir, 'planted.module.css');
  const dts = `${css}.d.ts`;
  const outcomes = [];
  try {
    mkdirSync(fixtureDir, { recursive: true });
    writeFileSync(css, '.alpha { color: red; }\n.betaTwo { color: blue; }\n', 'utf8');

    // 1. missing declaration is detected
    outcomes.push(['missing', build().some((a) => a.dtsPath === dts && !existsSync(a.dtsPath))]);

    // 2. stale declaration is detected
    writeFileSync(dts, '// stale\n', 'utf8');
    const stale = build().find((a) => a.dtsPath === dts);
    outcomes.push(['stale', stale !== undefined && readFileSync(dts, 'utf8') !== stale.content]);

    // 3. orphan declaration is detected
    writeFileSync(dts, stale?.content ?? '', 'utf8');
    unlinkSync(css);
    outcomes.push(['orphan', orphans().includes(dts)]);
  } finally {
    rmSync(fixtureDir, { recursive: true, force: true });
  }

  let failures = 0;
  for (const [rule, fired] of outcomes) {
    if (fired) console.log(`  ✓ gen-css-types/${rule} — rejected its violator`);
    else {
      console.error(`  ✗ gen-css-types/${rule} — did NOT reject its violator (gate is broken)`);
      failures++;
    }
  }
  process.exit(failures === 0 ? 0 : 1);
}

const artifacts = build();
const orphaned = orphans();

if (argv.includes('--check')) {
  const problems = [];
  for (const a of artifacts) {
    let current = null;
    try {
      current = readFileSync(a.dtsPath, 'utf8');
    } catch {
      problems.push(`${relative(repoRoot, a.dtsPath)} — missing`);
      continue;
    }
    if (current !== a.content) problems.push(`${relative(repoRoot, a.dtsPath)} — stale`);
  }
  for (const o of orphaned) {
    problems.push(`${relative(repoRoot, o)} — orphaned (its stylesheet was deleted)`);
  }

  if (problems.length) {
    console.error('✗ CSS Module declarations are out of date:');
    for (const p of problems) console.error(`    ${p}`);
    console.error('  Run `npm run gen:css-types` and commit the result.');
    process.exit(1);
  }
  console.log(`✓ CSS Module declarations up to date (${artifacts.length} stylesheet(s))`);
  process.exit(0);
}

for (const a of artifacts) writeFileSync(a.dtsPath, a.content, 'utf8');
for (const o of orphaned) unlinkSync(o);
console.log(
  `✓ generated ${artifacts.length} declaration(s)` +
    (orphaned.length ? `, removed ${orphaned.length} orphan(s)` : ''),
);

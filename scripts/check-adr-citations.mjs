#!/usr/bin/env node
// scripts/check-adr-citations.mjs
//
// ADR 0001 — a citation that does not resolve is worse than no citation at all.
//
// ADR 0001 fixes the cross-reference form as a bare `ADR 0029`, deliberately unlinked, so that
// one `grep -rn 'ADR 0029'` finds every place that decision is relied on — prose, source
// comments, gate failure messages and commit trailers alike. Everything this gate enforces
// follows from that one property:
//
//   dangling-citation   a cited number with no `docs/decisions/NNNN-*.md` behind it. Usually a
//                       typo, or a number reserved in a session whose record never landed.
//   malformed-citation  any spelling other than the bare one — hyphenated, lowercased, unpadded,
//                       run together, double-spaced. Not a resolution failure but a greppability
//                       failure, which is the entire reason the bare form exists. Reported rather
//                       than silently accepted, because a citation nobody can grep is exactly the
//                       failure the convention was chosen to prevent. The `--self-test` block
//                       below exhibits each rejected spelling; this comment does not, because
//                       `scripts/**` is inside the scan set and the gate would flag its own prose.
//   orphan-record       a record nothing else cites. WARNING only, never a build failure.
//   stale-index         `docs/decisions/README.md` is generated by `npm run adr -- index` and
//                       drifts silently — nothing else reads it, so nothing else notices.
//
// Usage:
//   node scripts/check-adr-citations.mjs
//   node scripts/check-adr-citations.mjs --self-test   plant a violator per rule, assert each fires

import { readFileSync, writeFileSync, mkdtempSync, rmSync, readdirSync, statSync, existsSync } from 'node:fs';
import { resolve, relative, join, sep, basename } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(import.meta.url), '..', '..');
const DECISIONS_DIR = resolve(repoRoot, 'docs/decisions');
const INDEX_FILE = resolve(DECISIONS_DIR, 'README.md');
const INDEX_REL = 'docs/decisions/README.md';

/**
 * `docs/decisions/NNNN-kebab-title.md` — the permanent-identifier filename shape from ADR 0001.
 *
 * The slug is case-tolerant on purpose: the corpus already contains
 * `0021-headless-primitives-className-render.md`, where the capital belongs to an identifier the
 * title quotes. A lowercase-only pattern silently drops that record from the known set, which
 * turns every one of its thirty-odd citations into a false `dangling-citation` — a gate failing
 * loudly for the wrong reason, which costs as much trust as one that never fires.
 */
const RECORD_RE = /^(\d{4})-[A-Za-z0-9][A-Za-z0-9-]*\.md$/;

/** The meta-record. It defines the citation convention rather than being invoked by it. */
const META_RECORD = '0001';

/**
 * Assembled rather than written inline wherever this file needs to name a *bad* citation, because
 * `scripts/**\/*.mjs` is inside this gate's own scan set: a literal violator in the self-test
 * fixtures below would be a real violation of the real repository, and the gate would fail itself.
 */
const TAG = 'ADR';

/**
 * One pattern matches every form, canonical and broken alike, and classification happens after —
 * a gate that only matched the canonical form could not see the citations it is supposed to fix.
 *
 * The leading lookbehind is what keeps `MADR`, `adrenaline` and the letters buried inside base64
 * integrity digests out of the results; the trailing one stops a 4-digit number being clipped out
 * of a longer run of digits.
 */
const CITATION_RE = /(?<![A-Za-z0-9_])(adr)([ \t]*[-–—_#]?[ \t]*)(\d{1,5})(?!\d)/gi;

const SKIP_DIRS = new Set(['node_modules', 'dist', 'storybook-static', 'coverage', '.vitest-reports']);

function toRel(abs) {
  return relative(repoRoot, abs).split(sep).join('/');
}

/**
 * Which files carry citations worth resolving. ADR 0001 requires every citation in the repository
 * to resolve, not only those inside `docs/decisions/`, so this deliberately reaches into source
 * comments and build config as well as prose.
 *
 * `CHANGELOG*` is excluded: release notes replay historical text verbatim, including citations
 * made by records that have since been superseded, and rewriting history to satisfy a linter is
 * the wrong repair.
 */
export function isScanned(rel) {
  if (rel.endsWith('.md')) return !basename(rel).startsWith('CHANGELOG');
  if (/^packages\/[^/]+\/src\/.+\.tsx?$/.test(rel)) return true;
  if (/^packages\/[^/]+\/[^/]+\.config\.(ts|mjs)$/.test(rel)) return true;
  if (/^scripts\/.+\.mjs$/.test(rel)) return true;
  if (/^\.storybook\/.+\.tsx?$/.test(rel)) return true;
  // CI configuration carries eighteen citations across four files — trusted publishing
  // (ADR 0039), the pinning rules (ADR 0043), the visual container (ADR 0042) and the workbench
  // deploy (ADR 0044). None of it was scanned until this line existed, so a dangling citation
  // there resolved to nothing and a record cited only from a workflow read as an orphan.
  if (/^\.github\/.+\.ya?ml$/.test(rel)) return true;
  if (/^[^/]+\.config\.(ts|mjs)$/.test(rel)) return true;
  return false;
}

/**
 * Dot-directories are skipped by the sweep, which matters for exactly one of them: `.claude/`
 * vendors the ADR skill, whose documentation explains the citation format using hyphenated
 * generic examples, and which ships the upstream MADR template with a status placeholder naming a
 * record number no project has. That is documentation *of* a convention, about no corpus in
 * particular — linting it would fail the build on third-party text this repository has no
 * business rewriting.
 *
 * `.storybook/` and `.github/` are scanned, but as explicit roots below rather than through the
 * sweep, so
 * opting a dot-directory in stays a deliberate act.
 */
function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  // Sorted: ADR 0033 forbids letting filesystem iteration order reach a gate's output.
  for (const entry of readdirSync(dir).sort()) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (entry.startsWith('.')) continue;
      walk(full, out);
    } else if (isScanned(toRel(full))) {
      out.push(full);
    }
  }
  return out;
}

function collect() {
  return [
    ...walk(repoRoot),
    ...walk(resolve(repoRoot, '.storybook')),
    ...walk(resolve(repoRoot, '.github')),
  ].sort();
}

function lineOf(text, index) {
  return text.slice(0, index).split('\n').length;
}

/**
 * Blank out fenced code blocks, keeping every character position so reported line numbers still
 * match the file on disk.
 *
 * Fenced blocks in this corpus hold examples — shell transcripts, sample frontmatter, the MADR
 * template — where a number is a placeholder illustrating a shape rather than a claim that a
 * record exists. Worse, the prose most likely to sit beside such a fence is prose *about* the
 * citation format, so scanning fences makes the gate fail on its own documentation. Citations
 * inside fences are also excluded from the cited set, so an example cannot keep a record from
 * being reported as an orphan.
 */
function blankFencedBlocks(md) {
  const lines = md.split('\n');
  const fenced = new Set();
  let opener = null;
  let openedAt = -1;

  for (let i = 0; i < lines.length; i++) {
    const marker = /^\s{0,3}(`{3,}|~{3,})/.exec(lines[i]);
    if (!marker) continue;
    if (opener === null) {
      opener = marker[1];
      openedAt = i;
    } else if (marker[1][0] === opener[0] && marker[1].length >= opener.length) {
      // A fence closes only on the same character, repeated at least as many times as the opener.
      for (let j = openedAt; j <= i; j++) fenced.add(j);
      opener = null;
    }
  }

  // An opener with no closer is malformed markdown, not a code block, so nothing is blanked for
  // it. Blanking to end-of-file would let one mistyped fence hide every citation after it — the
  // gate would go quiet and stay green, which is the exact failure ADR 0033 exists to close. When
  // in doubt this rule errs loud: a false positive gets argued about, a false negative does not.
  return lines.map((line, i) => (fenced.has(i) ? ' '.repeat(line.length) : line)).join('\n');
}

/**
 * Line numbers of `status:` inside a document's leading frontmatter.
 *
 * ADR 0001 closes the status vocabulary at `proposed | accepted | rejected | deprecated |
 * superseded by ADR-NNNN`, and that last one is hyphenated. It is the single place the
 * non-bare form is correct, so the style rule must stand down there — while the resolution
 * rule keeps applying, since a supersede link pointing at a record that does not exist is
 * precisely the rot worth catching.
 */
function frontmatterStatusLines(text) {
  const exempt = new Set();
  if (!text.startsWith('---\n')) return exempt;
  const lines = text.split('\n');
  for (let i = 1; i < lines.length; i++) {
    if (lines[i].trim() === '---') break;
    if (/^status\s*:/.test(lines[i])) exempt.add(i + 1);
  }
  return exempt;
}

function checkFile(absPath) {
  const rel = toRel(absPath);
  const raw = readFileSync(absPath, 'utf8');
  const markdown = rel.endsWith('.md');
  const text = markdown ? blankFencedBlocks(raw) : raw;
  const exemptLines = markdown ? frontmatterStatusLines(raw) : new Set();

  const citations = [];
  const problems = [];

  for (const m of text.matchAll(CITATION_RE)) {
    const [, word, separator, digits] = m;
    const line = lineOf(raw, m.index);
    const number = String(Number(digits)).padStart(4, '0');
    const canonical = word === TAG && separator === ' ' && digits.length === 4;

    citations.push({ rel, line, number });

    if (canonical || exemptLines.has(line)) continue;
    problems.push({
      rel,
      line,
      rule: 'malformed-citation',
      message:
        `\`${m[0]}\` — write citations bare as \`${TAG} ${number}\` (ADR 0001). The form is fixed so ` +
        `that \`grep -rn '${TAG} ${number}'\` finds every reference; this spelling hides from it.`,
    });
  }

  return { citations, problems };
}

function readStatus(text) {
  if (!text.startsWith('---\n')) return '';
  const end = text.indexOf('\n---', 4);
  const head = end === -1 ? text : text.slice(0, end);
  const m = /^status\s*:\s*["']?\s*(.*?)\s*["']?\s*$/m.exec(head);
  return (m?.[1] ?? '').toLowerCase();
}

function listRecords() {
  if (!existsSync(DECISIONS_DIR)) return [];
  return readdirSync(DECISIONS_DIR)
    .sort()
    .filter((file) => RECORD_RE.test(file))
    .map((file) => ({
      number: RECORD_RE.exec(file)[1],
      file,
      rel: `docs/decisions/${file}`,
      status: readStatus(readFileSync(join(DECISIONS_DIR, file), 'utf8')),
    }));
}

function checkCitations(records, citations) {
  const known = new Set(records.map((r) => r.number));
  return citations
    .filter((c) => !known.has(c.number))
    .map((c) => ({
      rel: c.rel,
      line: c.line,
      rule: 'dangling-citation',
      message:
        `cites ${TAG} ${c.number}, but \`docs/decisions/${c.number}-*.md\` does not exist. Fix the ` +
        `number, or write the record first — \`npm run adr -- next\` allocates one (ADR 0001).`,
    }));
}

/** Link targets in the generated index, e.g. `[0002](0002-npm-workspaces-monorepo.md)`. */
function indexTargets(indexText) {
  return new Set([...indexText.matchAll(/\((\d{4}-[A-Za-z0-9-]+\.md)\)/g)].map((m) => m[1]));
}

function checkIndex(records, indexText) {
  if (!indexText) {
    return [
      {
        rel: INDEX_REL,
        line: 1,
        rule: 'stale-index',
        message: `the generated index is missing. Run \`npm run adr -- index\` (ADR 0001).`,
      },
    ];
  }

  const listed = indexTargets(indexText);
  const onDisk = new Set(records.map((r) => r.file));
  const problems = [];

  // Both directions rot: a new record never reaches the table, and a renamed one leaves a row
  // pointing at a file that is gone. Neither shows up anywhere else, because nothing reads the
  // index except a human looking for a record.
  for (const r of records) {
    if (listed.has(r.file)) continue;
    problems.push({
      rel: INDEX_REL,
      line: 1,
      rule: 'stale-index',
      message:
        `does not list \`${r.file}\`. The index is generated, never hand-edited — run ` +
        `\`npm run adr -- index\` and commit the result (ADR 0001).`,
    });
  }

  for (const file of [...listed].sort()) {
    if (onDisk.has(file)) continue;
    problems.push({
      rel: INDEX_REL,
      line: 1,
      rule: 'stale-index',
      message:
        `links to \`${file}\`, which is not in \`docs/decisions/\`. Regenerate with ` +
        `\`npm run adr -- index\` (ADR 0001).`,
    });
  }

  return problems;
}

/**
 * A record is exempt from the orphan warning when it is the meta-record, or when it has already
 * been superseded — a superseded record is history, and history is not supposed to acquire new
 * references.
 */
function isOrphanEligible(record) {
  return record.number !== META_RECORD && !record.status.startsWith('superseded');
}

function findOrphans(records, citations) {
  const citedFrom = new Map();
  for (const c of citations) {
    if (!citedFrom.has(c.number)) citedFrom.set(c.number, new Set());
    citedFrom.get(c.number).add(c.rel);
  }

  return records.filter(isOrphanEligible).flatMap((r) => {
    // A record citing itself proves nothing depends on it, so self-references do not count.
    const external = [...(citedFrom.get(r.number) ?? [])].filter((rel) => rel !== r.rel);
    if (external.length > 0) return [];
    return [
      {
        rel: r.rel,
        line: 1,
        rule: 'orphan-record',
        message:
          `nothing outside this file cites ${TAG} ${r.number}. Cite it from the code or prose it ` +
          `governs, or supersede it — a decision nothing references is not governing anything.`,
      },
    ];
  });
}

function run() {
  const files = collect();
  const records = listRecords();

  const citations = [];
  const problems = [];
  for (const file of files) {
    const found = checkFile(file);
    citations.push(...found.citations);
    problems.push(...found.problems);
  }

  const indexText = existsSync(INDEX_FILE) ? readFileSync(INDEX_FILE, 'utf8') : '';
  problems.push(...checkCitations(records, citations), ...checkIndex(records, indexText));
  problems.sort((a, b) => a.rel.localeCompare(b.rel) || a.line - b.line || a.rule.localeCompare(b.rule));

  return {
    files,
    records,
    citations,
    problems,
    warnings: findOrphans(records, citations),
    eligible: records.filter(isOrphanEligible).length,
  };
}

if (process.argv.includes('--self-test')) {
  // ADR 0033 — a gate that cannot be shown to reject its own violator is decorative.
  //
  // The corpus rules take plain data, so their fixtures are a four-record synthetic corpus rather
  // than the real one. That keeps the self-test's verdict independent of the repository's current
  // state: a self-test that goes red because someone added an uncited record is not testing the
  // gate, it is testing the corpus.
  const RECORDS = [
    { number: '0001', file: '0001-meta.md', rel: 'docs/decisions/0001-meta.md', status: 'accepted' },
    { number: '0002', file: '0002-two.md', rel: 'docs/decisions/0002-two.md', status: 'accepted' },
    { number: '0003', file: '0003-three.md', rel: 'docs/decisions/0003-three.md', status: 'accepted' },
    {
      number: '0004',
      file: '0004-four.md',
      rel: 'docs/decisions/0004-four.md',
      status: `superseded by ${TAG}-0003`,
    },
  ];
  const cite = (number, rel = 'docs/prose.md') => ({ rel, line: 1, number });
  const renderIndex = (records) => records.map((r) => `| [${r.number}](${r.file}) | … |`).join('\n');

  const FILE_CASES = [
    ['malformed-citation', `Per ${TAG}-0012 the arrow points one way.`],
    ['malformed-citation', `Per ${TAG} 12 the arrow points one way.`],
    ['malformed-citation', `Per ${TAG.toLowerCase()} 0012 the arrow points one way.`],
    ['malformed-citation', `Per ${TAG}0012 the arrow points one way.`],
  ];

  /**
   * Over-firing is the specific hazard here, because three legal patterns look like violations:
   * the hyphenated form is mandatory inside a `status:` line, fenced blocks are full of example
   * numbers, and `MADR` / `ADRs` / base64 digests all contain the letters this gate hunts for.
   */
  const FILE_ALLOWED = [
    ['the bare canonical form', `This follows ${TAG} 0002 and ${TAG} 0003.`],
    ['numbers inside a fenced example', `\`\`\`\n${TAG}-0007 and ${TAG} 9999\n\`\`\`\n`],
    ['a supersede status line', `---\nstatus: "superseded by ${TAG}-0002"\ndate: 2026-01-01\n---\n`],
    ['prose that merely contains the letters', 'MADR-shaped ADRs, adrenaline, sha512-abcadr2def.'],
  ];

  const outcomes = [];
  // The fixture is torn down BEFORE any `process.exit()` — exiting skips `finally`.
  const fixtureDir = mkdtempSync(join(tmpdir(), 'nerey-citations-'));
  const fixture = join(fixtureDir, 'planted.md');
  try {
    for (const [rule, markdown] of FILE_CASES) {
      writeFileSync(fixture, markdown, 'utf8');
      outcomes.push([rule, checkFile(fixture).problems.some((p) => p.rule === rule)]);
    }
    for (const [name, markdown] of FILE_ALLOWED) {
      writeFileSync(fixture, markdown, 'utf8');
      const found = checkFile(fixture);
      const dangling = checkCitations(RECORDS, found.citations);
      const fired = [...found.problems, ...dangling];
      outcomes.push([`allows ${name}`, fired.length === 0, fired.map((p) => p.rule).join(', ')]);
    }

    // The fence exemption is the one place this gate can be talked into silence, so both of its
    // edges get a violator: a citation after a properly closed fence, and a citation after an
    // opener that is never closed. Either one going unseen means a single stray ``` can switch
    // the rule off for the rest of a document while the run stays green.
    const AFTER_FENCE = [
      ['dangling-citation (after a closed fence)', `\`\`\`\nexample\n\`\`\`\n\nBut see ${TAG} 9999.\n`],
      ['dangling-citation (after an unterminated fence)', `\`\`\`\nexample\n\nBut see ${TAG} 9999.\n`],
    ];
    for (const [label, markdown] of AFTER_FENCE) {
      writeFileSync(fixture, markdown, 'utf8');
      const found = checkCitations(RECORDS, checkFile(fixture).citations);
      outcomes.push([label, found.some((p) => p.rule === 'dangling-citation')]);
    }
  } finally {
    rmSync(fixtureDir, { recursive: true, force: true });
  }

  const CORPUS_CASES = [
    ['dangling-citation (unknown number)', () => checkCitations(RECORDS, [cite('9999')]).length === 1],
    [
      'stale-index (record missing from the index)',
      () => checkIndex(RECORDS, renderIndex(RECORDS.slice(0, 3))).length === 1,
    ],
    [
      'stale-index (index lists a record that is gone)',
      () => checkIndex(RECORDS, `${renderIndex(RECORDS)}\n| [0099](0099-deleted.md) | … |`).length === 1,
    ],
    [
      'orphan-record (nothing cites it)',
      () => findOrphans(RECORDS, [cite('0002')]).some((w) => w.rel.includes('0003')),
    ],
    [
      'orphan-record (only cites itself)',
      () =>
        findOrphans(RECORDS, [cite('0002'), cite('0003', RECORDS[2].rel)]).some((w) =>
          w.rel.includes('0003'),
        ),
    ],
  ];

  const CORPUS_ALLOWED = [
    ['citations that resolve', () => checkCitations(RECORDS, [cite('0002'), cite('0004')]).length === 0],
    ['an index in sync', () => checkIndex(RECORDS, renderIndex(RECORDS)).length === 0],
    [
      'an uncited meta-record and an uncited superseded record',
      () => findOrphans(RECORDS, [cite('0002'), cite('0003')]).length === 0,
    ],
  ];

  for (const [label, predicate] of CORPUS_CASES) outcomes.push([label, predicate()]);
  for (const [label, predicate] of CORPUS_ALLOWED) outcomes.push([`allows ${label}`, predicate()]);

  /**
   * The scan set, which was untested until it turned out to be wrong.
   *
   * `.github/**` carried eighteen citations that nothing resolved, and a record cited only from a
   * workflow read as an orphan. A shrinking scan set is the quietest way for this gate to stop
   * working: it keeps reporting a healthy number while looking at less and less, and the number
   * going UP is the only visible symptom of it having been too low.
   */
  const SCANNED = [
    ['scans a workflow', '.github/workflows/ci.yml'],
    ['scans a yaml config in .github', '.github/dependabot.yml'],
    ['scans a record', 'docs/decisions/0001-thing.md'],
    ['scans package source', 'packages/core/src/registry.ts'],
    ['scans a gate', 'scripts/check-adr-citations.mjs'],
    ['scans the workbench config', '.storybook/main.tsx'],
  ];
  const NOT_SCANNED = [
    ['a changelog', 'packages/core/CHANGELOG.md'],
    ['a lockfile', 'package-lock.json'],
    ['a reference image', 'packages/theme/src/visual/__screenshots__/x.png'],
    ['a workflow-shaped path outside .github', 'docs/workflows/ci.yml'],
  ];
  for (const [label, rel] of SCANNED) outcomes.push([`${label} — ${rel}`, isScanned(rel)]);
  for (const [label, rel] of NOT_SCANNED) outcomes.push([`allows skipping ${label}`, !isScanned(rel)]);

  let failures = 0;
  for (const [label, ok, detail] of outcomes) {
    const positive = !label.startsWith('allows ');
    if (ok) {
      console.log(
        `  ✓ check-adr-citations/${label} — ${positive ? 'rejected its violator' : 'stayed silent'}`,
      );
    } else {
      console.error(
        positive
          ? `  ✗ check-adr-citations/${label} — did NOT reject its violator (gate is broken)`
          : `  ✗ check-adr-citations/${label} — fired on legal input [${detail}] (gate over-fires)`,
      );
      failures++;
    }
  }
  process.exit(failures === 0 ? 0 : 1);
}

const { files, records, citations, problems, warnings, eligible } = run();

for (const w of warnings) {
  console.log(`  ⚠ ${w.rel}:${w.line}  [${w.rule}] ${w.message}`);
}
if (warnings.length) {
  const share = Math.round((warnings.length / Math.max(eligible, 1)) * 100);
  console.log(
    `  ⚠ ${warnings.length}/${eligible} citable record(s) (${share}%) are referenced by nothing. This ` +
      `does not fail the build — a record can be legitimately uncited for a while — but a corpus ` +
      `most of which nothing points at has stopped being load-bearing (ADR 0001).\n`,
  );
}

if (problems.length) {
  console.error(`✗ ADR citations: ${problems.length} violation(s) across ${files.length} scanned file(s)\n`);
  for (const p of problems) {
    console.error(`  ${p.rel}:${p.line}  [${p.rule}] ${p.message}`);
  }
  console.error(
    `\n  ADR 0001 fixes the citation form as a bare \`${TAG} 0029\`, unlinked, so one grep finds ` +
      `every reference. Records live in docs/decisions/.`,
  );
  process.exit(1);
}

console.log(
  `✓ ADR citations: ${citations.length} citation(s) in ${files.length} scanned file(s) resolve to ` +
    `${records.length} record(s); ${INDEX_REL} in sync`,
);

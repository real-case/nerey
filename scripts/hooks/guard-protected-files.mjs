#!/usr/bin/env node
// scripts/hooks/guard-protected-files.mjs
//
// PreToolUse guard (Claude Code hook). ADR 0034 — the rules that CLAUDE.md states in
// prose are enforced here as a deterministic block, so an agent cannot drift past them
// by good intentions.
//
// Blocks an Edit / Write / NotebookEdit when the target is:
//   • an ACCEPTED ADR (docs/decisions/NNNN-*.md, status: accepted) — accepted records
//     change only through a superseding record, never in place (ADR 0001).
//   • a GENERATED artifact — tokens.generated.ts, tokens.allowlist.json,
//     tokens.agent-rules.md, *.module.css.d.ts. These are rebuilt by `npm run gen:tokens`
//     / `npm run gen:css-types` from their real source (ADR 0023 / 0024). Hand-editing one
//     is invisible to the generator and reverts on the next run.
//   • the public-API snapshot or the data-attribute contract snapshot — these lock a
//     PUBLIC contract (ADR 0020 / 0028 / 0029); a change to one is a reviewed, deliberate
//     act with semver consequences, not an incidental edit.
//   • a real secrets file (.env, .env.<x>) other than .env.example.
//   • package-lock.json — regenerate it with npm, never hand-edit.
//
// Contract: hook payload on stdin; exit 2 with the reason on stderr to BLOCK (Claude is
// shown the reason and picks another path); exit 0 to allow. Fails OPEN on any unexpected
// error — a guard must never brick every edit because its own input shape changed.

import { existsSync, readFileSync } from 'node:fs';
import { basename, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(import.meta.url), '..', '..', '..');

// Out-of-band, auditable opt-out for the accepted-ADR immutability clause only. A human
// drops the sentinel file or sets the env var; an ordinary agent edit cannot create the
// conditions for its own bypass. Every use is logged to stderr.
const ADR_EDIT_WAIVER =
  process.env.NEREY_ADR_EDIT_WAIVER === '1' || existsSync(resolve(repoRoot, '.adr-edit-waiver'));

function block(reason) {
  process.stderr.write(`⛔ Blocked by guard-protected-files: ${reason}\n`);
  process.exit(2);
}

function readStdin() {
  try {
    return readFileSync(0, 'utf8');
  } catch {
    return '';
  }
}

let payload;
try {
  payload = JSON.parse(readStdin() || '{}');
} catch {
  process.exit(0);
}

const input = payload.tool_input ?? {};

// Bash branch: `vitest -u` regenerates snapshot baselines, including the public-API and
// data-attribute contract snapshots. Those encode a semver-relevant public contract
// (ADR 0020 / 0028 / 0029), so the update is a reviewed human action.
//
// The visual config is exempt, and the exemption is narrow on purpose. `vitest.visual.config.ts`
// includes only `*.visual.test.tsx` (ADR 0042), which carry no contract snapshot of any kind — so
// blocking it was this rule firing on the word `--update` rather than on what the command actually
// rewrites. The reference IMAGES are protected instead by rule 4 below, and unlike a JSON baseline
// a changed PNG shows up in a pull request as a picture, which is the review this rule exists to
// force.
if (payload.tool_name === 'Bash' && typeof input.command === 'string') {
  const visualOnly = /--config[= ]\S*vitest\.visual\.config\.ts/.test(input.command);
  if (!visualOnly && /\bvitest\b[^|;&\n]*\s--?u(pdate)?\b/.test(input.command)) {
    block(
      '`vitest -u` regenerates the public-API and data-attribute contract snapshots, which ' +
        'lock a PUBLIC contract with semver consequences (ADR 0020 / 0028 / 0029). Show the ' +
        'human the failing snapshot diff and ask them to run `npx vitest -u` themselves.',
    );
  }
  process.exit(0);
}

const filePath = input.file_path ?? input.notebook_path ?? input.path;
if (!filePath || typeof filePath !== 'string') process.exit(0);

const abs = resolve(filePath);
const relPosix = relative(repoRoot, abs).split(sep).join('/');
const base = basename(relPosix);

// 1. Secrets.
if (/^\.env(\..+)?$/.test(base) && base !== '.env.example') {
  block(`${relPosix} is a secrets file — values are human-provisioned and never tracked.`);
}

// 2. The lockfile.
if (base === 'package-lock.json') {
  block(
    'package-lock.json is generated by npm. Change dependencies in the relevant package.json ' +
      'and run `npm install`; never hand-edit the lockfile.',
  );
}

// 3. Generated artifacts (ADR 0023 / 0024).
const GENERATED = [
  /(^|\/)tokens\.generated\.ts$/,
  /(^|\/)tokens\.allowlist\.json$/,
  /(^|\/)tokens\.agent-rules\.md$/,
  /\.module\.css\.d\.ts$/,
];
if (GENERATED.some((re) => re.test(relPosix))) {
  const generator = relPosix.endsWith('.module.css.d.ts') ? 'npm run gen:css-types' : 'npm run gen:tokens';
  block(
    `${relPosix} is GENERATED and reverts on the next run of \`${generator}\`. Edit the real ` +
      `source instead — packages/theme/src/tokens.css for tokens, the .module.css file for ` +
      `class-name declarations — then run the generator.`,
  );
}

// 4. Contract baselines (ADR 0020 / 0028 / 0038).
//
// The committed JSON baselines are the ones this guard's header has always claimed to cover, and
// until ADR 0038 the pattern below matched only vitest's `__snapshots__` — so the three files that
// actually lock a public contract were editable by hand. Hand-editing one is how a MAJOR reaches
// npm labelled as a patch: the gate goes green because its expectation moved, not because the
// surface did. Each has an `--update-baseline` path that prints what it blessed; that is the way in.
// Visual references (ADR 0042) are the same kind of artifact in a different format. Deleting one
// is how a visual regression becomes a green run: the gate compares against what is on disk, so an
// absent image passes by having nothing to disagree with. Regeneration goes through the container,
// which is the only rasteriser CI agrees with.
if (/(^|\/)__screenshots__\//.test(relPosix)) {
  block(
    `${relPosix} is a visual reference image (ADR 0042). Regenerate the whole set with ` +
      `\`npm run test:visual:update\`, which captures it in the same Linux container CI compares ` +
      `against — never edit or delete one by hand.`,
  );
}

const BASELINES = /^docs\/design-system\/(public-api|api-signatures|data-contract|eslint-rules)\.json$/;
if (BASELINES.test(relPosix)) {
  const gate = relPosix.includes('data-contract')
    ? 'npm run check:data-contract -- --update-baseline'
    : relPosix.includes('api-signatures')
      ? 'npm run check:api-signatures -- --update-baseline'
      : relPosix.includes('eslint-rules')
        ? 'npm run check:eslint-rules -- --update-baseline'
        : 'npm run check:public-api -- --update-baseline';
  block(
    `${relPosix} is a CONTRACT BASELINE, not a file to edit. It records a public surface whose ` +
      `change has semver consequences (ADR 0020 / 0028 / 0029 / 0038). Re-bless it with ` +
      `\`${gate}\`, which prints every change it accepted, and land that in the same commit as ` +
      `the version bump — never to make a check pass.`,
  );
}

if (/(^|\/)__snapshots__\//.test(relPosix) || relPosix.endsWith('.snap')) {
  block(
    `${relPosix} is a contract snapshot. The public API surface and the data-* styling ` +
      `contract are public API (ADR 0020 / 0028) — a change is a reviewed act with semver ` +
      `consequences (ADR 0029). Show the human the diff rather than rewriting the baseline.`,
  );
}

// 5. Accepted ADRs are immutable — supersede, never edit in place (ADR 0001).
if (/^docs\/decisions\/\d{4}-.+\.md$/.test(relPosix)) {
  let text;
  try {
    text = readFileSync(abs, 'utf8');
  } catch {
    process.exit(0); // new record being created → allow
  }
  const fm = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const status = fm ? (fm[1].match(/^\s*status:\s*["']?([a-z]+)["']?/im)?.[1] ?? null) : null;
  if (status === 'accepted') {
    if (ADR_EDIT_WAIVER) {
      process.stderr.write(
        `⚠ guard-protected-files: ADR-edit waiver active — allowing in-place edit of ACCEPTED ` +
          `${relPosix}. This bypasses ADR 0001 immutability. Remove ./.adr-edit-waiver to restore ` +
          `the guard.\n`,
      );
      process.exit(0);
    }
    block(
      `${relPosix} is an ACCEPTED ADR — accepted records are never edited in place. Record a ` +
        `superseding ADR instead (\`npm run adr -- supersede --old NNNN --new MMMM\`), per ADR 0001.`,
    );
  }
}

process.exit(0);
